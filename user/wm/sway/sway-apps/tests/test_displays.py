def ipc_out(name, make="Unknown", model="Unknown", serial="Unknown", w=1920, h=1080, mhz=60000, x=0, y=0, scale=1.0,
            transform="normal", active=True, modes=None, vrr=False):
    o = {"name": name, "make": make, "model": model, "serial": serial, "active": active,
         "transform": transform, "adaptive_sync_status": "enabled" if vrr else "disabled",
         "modes": modes if modes is not None else [{"width": w, "height": h, "refresh": mhz}]}
    if active:
        lw, lh = d.logical_size(w, h, transform, scale)
        o.update({"scale": scale, "rect": {"x": x, "y": y, "width": lw, "height": lh},
                  "current_mode": {"width": w, "height": h, "refresh": mhz}})
    else:
        o["rect"] = {"x": 0, "y": 0, "width": 0, "height": 0}
    return o


