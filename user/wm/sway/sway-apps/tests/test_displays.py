class ScaleMath(unittest.TestCase):
    def test_4k_exact_scales_from_the_plan(self):
        got = {s: (w, h) for s, w, h in d.exact_scales(3840, 2160)}
        for s, size in ((1.25, (3072, 1728)), (1.5, (2560, 1440)), (1.6, (2400, 1350)),
                        (1.875, (2048, 1152)), (2.0, (1920, 1080))):
            self.assertEqual(got[s], size)
        self.assertNotIn(1.4, got)
        self.assertNotIn(1.2, got)   # the plan listed it; measured: sway makes 3840 at 1.2 3199 wide
        self.assertTrue(all(1.0 <= s <= 3.0 for s in got))

    def test_qhd_exact_scales(self):
        got = {s: (w, h) for s, w, h in d.exact_scales(2560, 1440)}
        self.assertEqual(got[1.25], (2048, 1152))
        self.assertEqual(got[1.6], (1600, 900))
        self.assertEqual(got[2.0], (1280, 720))
        self.assertNotIn(1.1, got)

    def test_transform_swaps_logical_size_only(self):
        normal = d.exact_scales(2560, 1440)
        rot = d.exact_scales(2560, 1440, "90")
        self.assertEqual([s for s, *_ in normal], [s for s, *_ in rot])
        self.assertIn((1.25, 1152, 2048), rot)
        self.assertIn((1.25, 1152, 2048), d.exact_scales(2560, 1440, "flipped-270"))
        self.assertEqual(d.logical_size(2560, 1440, "180", 1.25), (2048, 1152))

    def test_every_listed_scale_is_k_over_120_and_integral(self):
        for s, w, h in d.exact_scales(1920, 1200, "normal", 1.0, 3.0):
            k = round(s * 120)
            self.assertAlmostEqual(s, k / 120, places=5)
            self.assertEqual(1920 * 120 % k, 0)
            self.assertEqual((w, h), (1920 * 120 // k, 1200 * 120 // k))

    def test_is_exact(self):
        self.assertTrue(d.is_exact(3840, 2160, 1.6))
        self.assertTrue(d.is_exact(3840, 2160, 4 / 3))
        self.assertFalse(d.is_exact(3840, 2160, 1.4))
        self.assertFalse(d.is_exact(1920, 1200, 1.1))
        self.assertFalse(d.is_exact(3840, 2160, 1.61))   # not even a 1/120 step

    def test_logical_size_truncates_like_wlroots(self):
        self.assertEqual(d.logical_size(1920, 1200, "normal", 1.1), (1745, 1090))   # X13: dock placed at x=1745
        self.assertEqual(d.logical_size(3840, 2160, "normal", 1.6), (2400, 1350))
        self.assertEqual(d.logical_size(1920, 1200, "normal", 1.100000023841858), (1745, 1090))

    def test_scale_normalisation_and_format(self):
        self.assertEqual(d.norm_scale(1.100000023841858), 1.1)
        self.assertEqual(d.fmt_scale(1.0), "1")
        self.assertEqual(d.fmt_scale(4 / 3), "1.333333")
        self.assertEqual(round(float(d.fmt_scale(4 / 3)) * 120), 160)   # sway rounds it back to 160/120

    def test_dpi_suggestion(self):
        self.assertEqual(d.suggest_dpi(1.6), 154)
        self.assertEqual(d.suggest_dpi(1.25), 120)
        self.assertEqual(d.suggest_dpi(1.5), 144)
        self.assertEqual(d.suggest_dpi(1.1), 106)

    def test_modes(self):
        self.assertEqual(d.parse_mode("3840x2160@120.000Hz"), (3840, 2160, 120000))
        self.assertEqual(d.parse_mode("--custom 1920x1080@60Hz"), (1920, 1080, 60000))
        self.assertEqual(d.parse_mode("1280x720"), (1280, 720, 0))
        self.assertIsNone(d.parse_mode("big"))
        self.assertEqual(d.fmt_mode(1920, 1200, 60003), "1920x1200@60.003Hz")
        self.assertEqual(d.fmt_mode(1280, 720, 0), "1280x720")


class NwgImport(unittest.TestCase):
    def test_parse_blocks_quoted_and_desc_names(self):
        text = DESK_NWG + 'output "Dell Inc. DELL P2419H 20TZHC3" {\n  mode 1920x1080@60.0Hz\n  disable\n}\noutput HDMI-A-1 {\n pos 0 0\n}\n'
        p = d.parse_nwg(text)
        self.assertEqual(p["DP-1"]["mode"], "3840x2160@120.0Hz")
        self.assertEqual(p["DP-2"]["transform"], "90")
        self.assertEqual(p["Dell Inc. DELL P2419H 20TZHC3"]["enabled"], "no")
        self.assertEqual(p["HDMI-A-1"]["pos"], "0 0")

    def test_desk_import_maps_connectors_to_hw_ids(self):
        lay, notes = d.import_nwg(DESK_NWG, d.connector_map(d.live(DESK_IPC)))
        self.assertEqual(notes, [])
        self.assertEqual(set(lay), {SAMSUNG, NSL})
        s = lay[SAMSUNG]
        self.assertEqual((s.mode, s.x, s.y, s.scale, s.transform, s.scale_filter, s.adaptive_sync, s.enabled),
                         ("3840x2160@120.000Hz", 2103, 1394, 1.5, "normal", "nearest", False, True))
        n = lay[NSL]
        self.assertEqual((n.mode, n.x, n.y, n.scale, n.transform), ("2560x1440@144.000Hz", 4663, 786, 1.25, "90"))
        self.assertEqual(n.connector, "DP-2")

    def test_import_matches_the_live_layout_exactly(self):
        lay, _ = d.import_nwg(DESK_NWG, d.connector_map(d.live(DESK_IPC)))
        for o in d.live(DESK_IPC):
            self.assertTrue(lay[o.hw_id].same_layout(o.conf), o.name)

    def test_unknown_connector_keeps_its_name(self):
        lay, notes = d.import_nwg('output "HDMI-A-9" {\n mode 1920x1080@60.0Hz\n pos 10 20\n scale 1.100000023841858\n}\n', {})
        self.assertIn("HDMI-A-9", lay)
        self.assertEqual(lay["HDMI-A-9"].scale, 1.1)
        self.assertTrue(notes and "HDMI-A-9" in notes[0])


class _TempState(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.dir = Path(self._tmp.name)
        self._saved = (paths.STATE_DIR, paths.LOCAL_STATE_DIR, paths.SWAY_FEATURES, paths.XDG_CONFIG_HOME)
        paths.STATE_DIR = self.dir / "state"
        paths.LOCAL_STATE_DIR = self.dir / "local"
        paths.XDG_CONFIG_HOME = self.dir / "cfg"
        paths.SWAY_FEATURES = frozenset({"owns_outputs", "xwayland_zero_scaling"})
        paths.STATE_DIR.mkdir(parents=True)
        self.no_sway = mock.patch.object(swayipc, "available", return_value=False)
        self.no_sway.start()

    def tearDown(self):
        self.no_sway.stop()
        paths.STATE_DIR, paths.LOCAL_STATE_DIR, paths.SWAY_FEATURES, paths.XDG_CONFIG_HOME = self._saved
        self._tmp.cleanup()

    def state(self, profile: dict | None = None) -> st.State:
        c, p = paths.STATE_DIR / "common.json", paths.STATE_DIR / "P.json"
        c.write_text(json.dumps({"version": 1}))
        p.write_text(json.dumps({"version": 1, **(profile or {})}))
        return st.State(c, p)


class Render(_TempState):
    def test_nothing_without_the_feature(self):
        paths.SWAY_FEATURES = frozenset()
        s = self.state({"settings": {"displays": {"outputs": {SAMSUNG: {"mode": "3840x2160@120.000Hz"}}}}})
        self.assertEqual(d.render_include(s), "")

    def test_blocks_keyed_by_hw_id(self):
        s = self.state()
        lay, _ = d.import_nwg(DESK_NWG, d.connector_map(d.live(DESK_IPC)))
        d.store(s, lay)
        text = d.render_include(s)
        self.assertIn(f'output "{SAMSUNG}" {{\n    mode 3840x2160@120.000Hz\n    position 2103 1394\n    scale 1.5\n'
                      f'    transform normal\n    adaptive_sync off\n    scale_filter nearest\n    enable\n}}', text)
        self.assertIn(f'output "{NSL}" {{', text)   # the NSL's padded model spaces survive
        self.assertNotIn('"DP-1"', text)
        self.assertLess(text.index(NSL), text.index(SAMSUNG))   # ordered top to bottom

    def test_disabled_output(self):
        s = self.state()
        d.store(s, {"HEADLESS-2": d.OutputConf(mode="1280x720", enabled=False)})
        self.assertIn('output "HEADLESS-2" {\n    disable\n}', d.render_include(s))

    def test_all_unknown_hw_id_falls_back_to_connector(self):
        lv = d.live([ipc_out("HEADLESS-1"), ipc_out("eDP-1", "Lenovo Group Limited", "0x41A0", "Unknown")])
        with mock.patch.object(paths, "E2E", False):
            lv = d.live([ipc_out("HEADLESS-1"), ipc_out("eDP-1", "Lenovo Group Limited", "0x41A0", "Unknown")])
        self.assertEqual([o.hw_id for o in lv], ["Lenovo Group Limited 0x41A0 Unknown"])   # sway's placeholder skipped
        with mock.patch.object(paths, "E2E", True):
            lv = d.live([ipc_out("HEADLESS-1"), ipc_out("eDP-1", "Lenovo Group Limited", "0x41A0", "Unknown")])
        self.assertEqual([o.hw_id for o in lv], ["HEADLESS-1", "Lenovo Group Limited 0x41A0 Unknown"])
        s = self.state()
        d.store(s, {o.hw_id: o.conf for o in lv})
        text = d.render_include(s)
        self.assertIn('output "HEADLESS-1" {', text)
        self.assertIn('output "Lenovo Group Limited 0x41A0 Unknown" {', text)

    def test_nwg_fallback_before_import(self):
        s = self.state()
        (paths.XDG_CONFIG_HOME / "sway").mkdir(parents=True)
        d.nwg_file().write_text(DESK_NWG)
        with mock.patch.object(d, "live", return_value=d.live(DESK_IPC)):
            text = d.render_include(s)
        self.assertIn(f'output "{SAMSUNG}"', text)
        self.assertIn("not imported yet", text)
        d.store(s, {}, imported_from="x")   # imported once, then emptied: no fallback any more
        self.assertNotIn("output", d.render_include(s).split("\n", 2)[-1])

    def test_xwayland_dpi_only_with_zero_scaling(self):
        s = self.state({"settings": {"displays": {"xwayland_dpi": 154}}})
        self.assertIn("xwayland_dpi 154", d.render_include(s))
        paths.SWAY_FEATURES = frozenset({"owns_outputs"})
        self.assertNotIn("xwayland_dpi", d.render_include(s))

    def test_dpi_default_is_nix(self):
        s = self.state()
        with mock.patch.dict(os.environ, {"SWAY_APPS_XWAYLAND_DPI": "144"}):
            self.assertEqual(d.effective_dpi(s), (144, "nix default"))
            self.assertNotIn("xwayland_dpi", d.render_include(s))
            d.store(s, dpi=120)
            self.assertEqual(d.effective_dpi(s), (120, "profile"))

    def test_store_writes_the_profile_layer_only(self):
        s = self.state()
        d.store(s, {SAMSUNG: d.OutputConf(scale=1.6)})
        s.write()
        prof = json.loads((paths.STATE_DIR / "P.json").read_text())
        self.assertEqual(prof["settings"]["displays"]["outputs"][SAMSUNG]["scale"], 1.6)
        self.assertFalse(json.loads((paths.STATE_DIR / "common.json").read_text()).get("settings"))

    def test_render_validates_with_sway(self):
        import shutil
        if not shutil.which(paths.SWAY_BIN):
            self.skipTest("no sway binary")
        s = self.state()
        lay, _ = d.import_nwg(DESK_NWG, d.connector_map(d.live(DESK_IPC)))
        d.store(s, lay)
        paths.SWAY_FEATURES = frozenset({"owns_outputs"})   # xwayland_dpi needs the patched sway
        ok, out = swayipc.validate_config_text(d.render_include(s))
        self.assertTrue(ok, out)


class SaveRules(_TempState):
    def test_untouched_runtime_disable_is_never_saved(self):
        lid_closed = [ipc_out("eDP-1", "Lenovo Group Limited", "0x41A0", "Unknown", 1920, 1200, active=False),
                      ipc_out("HDMI-A-1", "Dell Inc.", "DELL P2419H", "20TZHC3", x=1745, scale=1.0)]
